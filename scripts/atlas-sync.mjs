/* ── <Name>.md ──────────────────────────────────────────── */

/**
 * A Figma description replaces the repo-written guidance only when it IS guidance.
 * A spec summary ("3 variants × 3 sizes") is a Figma content gap, not documentation:
 * keep the existing doc and file the gap as a discrepancy.
 */
const isGuidance = (d) => /when to use|when not to/i.test(d) || d.length >= 200

// Every component doc carries a generated API block (import, props, subcomponents) so a prototype
// never has to open component source for a prop name.
const API_BEGIN = "<!-- BEGIN:generated-api -->"
const API_END = "<!-- END:generated-api -->"
const apiSection = (c) => [
  API_BEGIN,
  "",
  "## API",
  "```tsx",
  `import { ${c.api.map((a) => a.name).join(", ")} } from "@atlas/ui-web/${c.tier}/${c.name}/${c.name}"`,
  "```",
  ...c.api.flatMap((a) => [
    "",
    `**${a.name}**${a.base ? ` — also accepts ${a.base}` : ""}`,
    ...(a.props.length ? a.props.map((p) => `- \`${p.name}${p.required ? "" : "?"}: ${p.type}\``) : ["- no own props"]),
  ]),
  API_END,
].join("\n")

const docsReplaced = []
for (const c of comps) {
  const rel = `atlas/${c.name}.md`
  const abs = path.join(ROOT, rel)
  const raw = c.figma?.description?.trim()
  if (raw && !isGuidance(raw)) {
    D(c.name, "figma", `Figma description is a spec summary, not usage guidance: "${raw}".`,
      "rewrite the Figma description as what it is · when to use · when not to use · do/don't (phase 3)", "sync:description")
  }
  const description = raw && isGuidance(raw) ? raw : null
  if (description) {
    docsReplaced.push(c.name)
    write(rel, [
      `<!-- ${HEADER} -->`,
      "",
      `# ${c.name}`,
      description,
      "",
      "## Variants",
      (c.variants ?? []).join(" · ") || "—",
      "",
      "## Sizes",
      (c.sizes ?? []).join(" · ") || "—",
      "",
      apiSection(c),
      "",
    ].join("\n"))
  } else if (fs.existsSync(abs)) {
    // no Figma description yet — keep the existing guidance, refresh the stamp and the API block
    const body = read(abs).replace(/^<!-- GENERATED[^>]*-->/, `<!-- ${HEADER} -->`)
    write(rel, upsertSection(body, API_BEGIN, API_END, apiSection(c)))
  }
}

/* ── tokens ─────────────────────────────────────────────── */

const tok = tokens()
// Figma MCP exposes variables per node, not a full variable table, so tokens stay
// repo-derived from packages/tokens/atlas.tokens.css until a pull carries variables.
const tokenSource = pull?.variables ? source : "repo-derived (packages/tokens/atlas.tokens.css)"
write("atlas/tokens.json", compactJson({
  _generated: stamp(tokenSource, pull?.variables ? syncedAt : null),
  source: tokenSource,
  syncedAt: pull?.variables ? syncedAt : null,
  figmaVersion: pull?.variables ? figmaVersion : null,
  note: "Semantic tokens and layout scales only. Primitive colour ramps (--atlas-color-*) are never used in app code.",
  semantic: tok.semantic,
  scales: tok.scales,
}))

// tokens.md keeps its curated body; the layout/platform groups are rendered between markers
const LAYOUT_BEGIN = "<!-- BEGIN:generated-layout-tokens -->"
const LAYOUT_END = "<!-- END:generated-layout-tokens -->"
const layoutSection = [
  LAYOUT_BEGIN,
  ...Object.entries(LAYOUT_GROUPS).flatMap(([title, prefixes]) => [
    "", `## ${title}`,
    prefixes.map((p) => Object.entries(tok.scales)
      .filter(([k]) => k.startsWith(`--atlas-${p}`))
      .map(([k, v]) => `\`${k.slice(8)}\` ${v}`).join(" · ")).filter(Boolean).join("\n"),
  ]),
  LAYOUT_END,
].join("\n")

for (const rel of ["atlas/tokens.md", "atlas/README.md"]) {
  const abs = path.join(ROOT, rel)
  if (!fs.existsSync(abs)) continue
  let body = read(abs).replace(/^<!-- GENERATED[^>]*-->/, `<!-- ${HEADER} -->`)
  if (rel === "atlas/tokens.md") {
    body = upsertSection(body, LAYOUT_BEGIN, LAYOUT_END, layoutSection)
  }
  write(rel, body)
}

/* ── state/discrepancies.json ───────────────────────────── */

const discPath = path.join(ATLAS, "state/discrepancies.json")
const disc = JSON.parse(read(discPath))
const existing = disc.discrepancies ?? []
const nextId = () => {
  const max = Math.max(0, ...existing.map((d) => parseInt(String(d.id).replace(/\D/g, ""), 10) || 0))
  return `DISC-${String(max + 1).padStart(3, "0")}`
}
const sameAs = (a, b) => a.component === b.component && a.issue === b.issue

for (const d of drift) {
  const hit = existing.find((e) => sameAs(e, d))
  if (hit) {
    hit.status = "open"
    hit.side = d.side
    hit.resolution = d.resolution
    hit.detectedBy = d.detectedBy
    hit.lastSeen = syncedAt ?? today()
  } else {
    existing.push({ id: nextId(), component: d.component, side: d.side, status: "open",
      issue: d.issue, resolution: d.resolution, detectedBy: d.detectedBy,
      firstSeen: syncedAt ?? today(), lastSeen: syncedAt ?? today() })
  }
}
// sync-detected entries that no longer drift are closed by the sync
const autoClosed = []
for (const e of existing) {
  if (detectors.has(e.detectedBy) && e.status === "open" && !drift.some((d) => sameAs(e, d))) {
    e.status = "closed"
    e.closedAt = syncedAt ?? today()
    e.closedBy = e.detectedBy
    autoClosed.push(e.id)
  }
}
write("atlas/state/discrepancies.json", compactJson({
  ...disc, _generated: HEADER, syncedAt, figmaVersion, discrepancies: existing,
}))

/* ── state stamps ───────────────────────────────────────── */

// state files are repo state, not Figma content — the stamp records only when the sync ran
for (const name of ["status", "decisions", "candidates"]) {
  const rel = `atlas/state/${name}.json`
  const json = JSON.parse(read(path.join(ROOT, rel)))
  write(rel, compactJson({
    ...json,
    _generated: `GENERATED — do not hand-edit. regenerated by atlas-figma-sync${syncedAt ? ` at ${syncedAt}` : ""}.`,
    syncedAt, figmaVersion,
  }))
}

